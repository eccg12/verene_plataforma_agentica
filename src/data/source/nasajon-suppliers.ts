  readonly spe: SpeId
  readonly razaoSocial: string
  readonly nomeFantasia: string | null
  readonly naturezaPessoa: NaturezaPessoa
  /** CNPJ ou CPF exatamente como veio no extrato, com ou sem máscara. */
